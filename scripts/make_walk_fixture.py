"""Fixture for the walking-guidance test: a real plan and a real detour on the local graph.

    python scripts/make_walk_fixture.py     # writes fixtures/walk_track_p1.json

Pair p1 (public places from fixtures/nyc_origins.json): A's leg to the meetup point and the
shared leg to the destination from the top candidate; a street node 80-150 m off A's leg near
40% of the way; and the route the re-plan endpoint gives from that node to the meetup point.
The GPS track itself is simulated in the test (backend/tests/js/walk.test.js).
"""

import json
import os

os.environ["USE_MOCKS"] = "false"

import numpy as np  # noqa: E402
from _common import ROOT, load_cases  # noqa: E402

from app.core.config import get_settings  # noqa: E402
from app.core.geo import haversine_m  # noqa: E402
from app.providers.local_routing import LocalRouting, load_graph  # noqa: E402
from app.providers.route_pois import load_route_pois  # noqa: E402
from app.providers.snapshot_places import SnapshotPlaces, load_snapshot  # noqa: E402
from app.services.planner import plan_walk  # noqa: E402


def main() -> None:
    s = get_settings()
    graph = load_graph(s.graph_path)
    routing = LocalRouting(graph, pois=load_route_pois(s.route_pois_path))
    places = SnapshotPlaces(load_snapshot(s.places_snapshot_path), fallback=None)
    case = next(c for c in load_cases() if c["id"] == "p1")
    plan = plan_walk(case["a"], case["b"], case["intent"], places, routing, case["depart_at"])
    c = plan.candidates[0]
    meet, dest = plan.places[c.meeting_place_id], plan.places[c.endpoint_place_id]
    a_leg = c.a_leg.geometry
    pivot = a_leg[int(len(a_leg) * 0.4)]

    # A street node 80-150 m from every point of A's leg, nearest to the 40% point.
    pts = np.array(a_leg)
    best = None
    for k in graph.tree.query_ball_point(np.array(graph._xy(*pivot)).ravel(), 250):
        node = (float(graph.lat[k]), float(graph.lon[k]))
        d_route = min(haversine_m(*node, *p) for p in pts)
        if 80 <= d_route <= 150:
            d = haversine_m(*node, *pivot)
            if best is None or d < best[0]:
                best = (d, node, d_route)
    _, detour, d_route = best
    replan = routing.walk(detour, (meet.lat, meet.lon))

    out = {
        "note": "Generated by scripts/make_walk_fixture.py from the local OSM graph (ODbL). Public places only.",
        "meetup": {"name": meet.name, "lat": meet.lat, "lon": meet.lon},
        "destination": {"name": dest.name, "lat": dest.lat, "lon": dest.lon},
        "a_leg": a_leg, "shared_leg": c.shared_leg.geometry,
        "a_steps": c.a_leg.steps, "shared_steps": c.shared_leg.steps,
        "a_pois": c.a_leg.pois, "shared_pois": c.shared_leg.pois,
        "detour_point": list(detour), "detour_distance_from_route_m": round(d_route, 1),
        "replan_leg": replan.geometry, "replan_steps": replan.steps, "replan_pois": replan.pois,
    }
    path = ROOT / "fixtures" / "walk_track_p1.json"
    path.write_text(json.dumps(out) + "\n")
    print(f"wrote {path.relative_to(ROOT)}: a_leg {len(a_leg)} pts ({c.a_leg.distance_m:.0f} m), "
          f"shared {len(c.shared_leg.geometry)} pts, detour {d_route:.0f} m off, replan {len(replan.geometry)} pts")


if __name__ == "__main__":
    main()
